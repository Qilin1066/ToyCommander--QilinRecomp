namespace qilin {

namespace {

constexpr size_t kChunkFunctions = 256;

// Writes `content` to `path` only if it differs. Returns whether it wrote.
bool update_file(const std::filesystem::path& path, const std::string& content) {
    {
        std::ifstream in(path, std::ios::binary);
        if (in) {
            const std::string old{std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>()};
            if (old == content) return false;
        }
    }
    std::ofstream out(path, std::ios::binary);
    out.write(content.data(), static_cast<std::streamsize>(content.size()));
    if (!out.flush()) throw std::runtime_error(std::format("cannot write {}", path.string()));
    return true;
}

}  // namespace

LiftSummary write_lifted(const BootFile& boot, const Cfg& cfg, std::span<const Region> regions, const std::filesystem::path& dir,
                         const LiftOptions& options, std::string_view version) {
    const auto plan_of = [&](uint32_t a) {
        for (const Region& r : regions)
            if (a >= r.begin && a < r.end) return r.plan;
        return Plan::lift;
    };
    const Lifter lifter(boot, cfg);
    std::filesystem::create_directories(dir);
    const std::string banner = std::format("// Generated by qilin {} from a boot file with SHA-256 {}.\n"
                                           "// Output lifted from the game is derived from it: never commit it.\n",
                                           version, boot.sha256);
    std::string header = banner + "#pragma once\n#include \"guest.hpp\"\n\nnamespace qilin::gen {\n";
    std::string table = banner + "#include \"functions.hpp\"\n\nnamespace qilin::rt {\nextern const FnEntry g_functions[] = {\n";
    std::string stubs = banner + "#include \"functions.hpp\"\n\nnamespace qilin::gen {\n";
    std::vector<std::string> chunks;
    LiftSummary sum;
    std::string details;
    size_t index = 0;
    for (const auto& [entry, f] : cfg.functions) {
        if (index++ % kChunkFunctions == 0) chunks.emplace_back();
        header += std::format("void {}(rt::Context& c);\n", fn_name(entry));
        table += std::format("    {{0x{:08X}u, gen::{}}},\n", entry, fn_name(entry));
        if (plan_of(entry) == Plan::replace) {
            stubs += std::format("void {}(rt::Context& c) {{ rt::unregistered(0x{:08X}u, c.pr); }}\n", fn_name(entry), entry);
            ++sum.replaced;
            continue;
        }
        const bool in_range = !options.range || (entry >= options.range->first && entry < options.range->second);
        const bool orphan = f.origin == Origin::orphan && !options.orphans;
        if (!in_range || orphan) {
            stubs += std::format("void {}(rt::Context&) {{ rt::not_lifted(0x{:08X}u); }}\n", fn_name(entry), entry);
            ++(orphan ? sum.unreferenced : sum.outside);
            continue;
        }
        const LiftResult r = lifter.lift(f);
        if (r.ok) {
            chunks.back() += r.code + "\n";
            ++sum.lifted;
            continue;
        }
        stubs += std::format("void {}(rt::Context&) {{ rt::not_lifted(0x{:08X}u); }}\n", fn_name(entry), entry);
        ++sum.failed;
        sum.failures[r.why.substr(0, r.why.find(':'))].push_back(entry);
        details += std::format("{} at {:08X}: {}\n", fn_name(entry), r.fail_at, r.why);
    }
    header += "}  // namespace qilin::gen\n";
    table += "};\nextern const size_t g_function_count = sizeof(g_functions) / sizeof(g_functions[0]);\n}  // namespace qilin::rt\n";
    stubs += "}  // namespace qilin::gen\n";
    sum.written += update_file(dir / "functions.hpp", header);
    sum.written += update_file(dir / "table.cpp", table);
    sum.written += update_file(dir / "stubs.cpp", stubs);
    std::set<std::string> names;
    if (chunks.empty()) chunks.emplace_back();
    for (size_t i = 0; i < chunks.size(); ++i) {
        const std::string name = std::format("lifted_{:03}.cpp", i);
        names.insert(name);
        sum.written += update_file(dir / name, banner + "#include \"functions.hpp\"\n\nnamespace qilin::gen {\n\n" + chunks[i] +
                                                   "}  // namespace qilin::gen\n");
    }
    for (const auto& e : std::filesystem::directory_iterator(dir)) {  // chunks left by an earlier run over more functions
        const std::string name = e.path().filename().string();
        if (name.starts_with("lifted_") && name.ends_with(".cpp") && !names.contains(name)) {
            std::filesystem::remove(e.path());
            ++sum.removed;
        }
    }
    sum.report = std::format("{} functions: {} lifted, {} not lifted, {} replaced (stubs), {} unreferenced (not lifted), {} outside --range\n",
                             cfg.functions.size(), sum.lifted, sum.failed, sum.replaced, sum.unreferenced, sum.outside);
    for (const auto& [why, fns] : sum.failures) sum.report += std::format("  {:5}  {}\n", fns.size(), why);
    sum.report += details;
    sum.written += update_file(dir / "lift_report.txt", sum.report);
    return sum;
}

}  // namespace qilin
