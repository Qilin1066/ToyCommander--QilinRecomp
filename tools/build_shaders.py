#!/usr/bin/env python3
"""Compile the game's shaders (<game>/shaders/) to SPIR-V and write
<game>/src/shaders.inc; likewise host/shaders/ (the window's picture) to
host/src/shaders.inc.

The generated files are committed, so building the game needs no shader
compiler; run this (it needs glslangValidator) after changing a shader.

Each header records a SHA-256 of its sources. `--check` (CI) fails if that
hash doesn't match, meaning someone changed a shader without regenerating. It
needs no compiler, because SPIR-V bytes differ between glslang versions. If
glslangValidator is installed, it also compiles each shader, so a broken one
fails too.
"""
import hashlib
import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
# The game's folder: the one beside host/ that has shaders/.
GAME = next(d for d in sorted(ROOT.iterdir()) if d.name != "host" and (d / "shaders").is_dir())
# (source, name in shaders.inc, extra glslang arguments)
SHADERS = [
    ("pvr.vert", "kPvrVert", []),
    ("pvr.frag", "kPvrFrag", []),
    # Punch-through polygons: texels under the alpha reference are discarded.
    ("pvr.frag", "kPvrFragPunch", ["-DPUNCH_THROUGH"]),
    # The translucent list in auto-sort mode: fragments onto per-pixel lists, then sorted and blended.
    ("pvr.frag", "kPvrFragSorted", ["-DSORTED"]),
    ("sort.comp", "kSortComp", []),
]
HOST_SHADERS = [
    ("present.vert", "kPresentVert", []),
    ("plain.frag", "kPlainFrag", []),
    ("crt.frag", "kCrtFrag", []),
]
# (sources, generated file, shaders)
GROUPS = [
    (GAME / "shaders", GAME / "src/shaders.inc", SHADERS),
    (ROOT / "host/shaders", ROOT / "host/src/shaders.inc", HOST_SHADERS),
]


def sources_hash(src: pathlib.Path, shaders) -> str:
    h = hashlib.sha256(repr(shaders).encode())  # the variants too, not just the files
    for f in sorted(src.iterdir()):
        if f.is_file():
            h.update(f.name.encode() + b"\0")
            h.update(f.read_bytes().replace(b"\r\n", b"\n") + b"\0")
    return h.hexdigest()


def compile_one(src: pathlib.Path, out: pathlib.Path, extra=()) -> bytes:
    subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.3", *extra, "-o", str(out), str(src)],
                   check=True, stdout=subprocess.DEVNULL)
    return out.read_bytes()


def check() -> int:
    failed = 0
    for src, target, shaders in GROUPS:
        stamp = f"// Sources: {sources_hash(src, shaders)}"
        lines = target.read_text().splitlines() if target.exists() else []
        if stamp not in lines[:4]:
            print(f"{target.relative_to(ROOT)} is out of date: run tools/build_shaders.py", file=sys.stderr)
            failed = 1
            continue
        if shutil.which("glslangValidator"):
            with tempfile.TemporaryDirectory() as tmp:
                for name, _, extra in shaders:
                    compile_one(src / name, pathlib.Path(tmp) / "out.spv", extra)
    if not shutil.which("glslangValidator"):
        print("glslangValidator not found: checked the hashes only")
    return failed


def build(src: pathlib.Path, target: pathlib.Path, shaders) -> None:
    lines = [f"// Generated by tools/build_shaders.py from {src.relative_to(ROOT).as_posix()}/: do not edit.",
             f"// Sources: {sources_hash(src, shaders)}", "#pragma once", "#include <cstdint>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for name, ident, extra in shaders:
            b = compile_one(src / name, pathlib.Path(tmp) / "out.spv", extra)
            words = struct.unpack(f"<{len(b) // 4}I", b)
            lines.append(f"inline constexpr uint32_t {ident}[] = {{")
            for i in range(0, len(words), 8):
                lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
            lines.append("};")
    target.write_text("\n".join(lines) + "\n")


def main() -> int:
    if "--check" in sys.argv:
        return check()
    for group in GROUPS:
        build(*group)
    return 0


if __name__ == "__main__":
    sys.exit(main())
